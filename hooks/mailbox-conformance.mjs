/** A deterministic PRNG, so a fuzz failure is reproducible and a green run is not luck. */
function rng(seed) {
	let state = seed >>> 0;
	return () => {
		state = (state * 1664525 + 1013904223) >>> 0;
		return state / 4294967296;
	};
}

const FUZZ_ALPHABET = "abcXYZ019 -_/.…é!@#$%^&*()[]{}\\|;:'\"<>,?~`+=\t\n";

function fuzzInputs(count) {
	const next = rng(20260806);
	const inputs = [];
	for (let i = 0; i < count; i++) {
		const make = (max) => {
			const length = Math.floor(next() * max);
			let out = "";
			for (let j = 0; j < length; j++) out += FUZZ_ALPHABET[Math.floor(next() * FUZZ_ALPHABET.length)];
			return out;
		};
		inputs.push({ cwd: `/x/${make(14)}`, sessionId: make(40) });
	}
	return inputs;
}

