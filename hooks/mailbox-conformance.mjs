// ── extraction: Swift ────────────────────────────────────────────────────────────────────

/**
 * Read `Handle.init?(validating:)`'s rule out of the Swift source and return something that
 * can be executed against a candidate.
 *
 * Deliberately STRICT: the initializer's body is normalized to one line and consumed by three
 * patterns, and anything left over is a hard failure naming the leftover text. So a rule this
 * harness cannot model turns the gate red instead of being silently skipped — which matters
 * more than usual here, because PR #244 is open and moving exactly this rule. Today's
 * `development` states trim + non-empty; #244 adds `[a-z0-9-]` as a spelled-out `Set` literal,
 * chosen that way so it could "be compared against their `slug` by eye". Both parse.
 */
function extractSwiftHandleRule(source) {
	const lines = source.split("\n");
	const start = lines.findIndex((line) => /^\s*package init\?\(validating candidate: String\) \{\s*$/.test(line));
	if (start < 0) {
		throw new Error("Handle.swift: no `package init?(validating candidate: String) {` — the alphabet check is measuring nothing");
	}
	const indent = lines[start].match(/^\s*/)[0];
	const end = lines.findIndex((line, i) => i > start && line === `${indent}}`);
	if (end < 0) throw new Error("Handle.swift: init?(validating:) has no closing brace at its own indentation");

	const normalized = `${lines
		.slice(start + 1, end)
		.map((line) => line.replace(/\/\/.*$/, ""))
		.join(" ")
		.replace(/\s+/g, " ")
		.trim()} `;

	let rest = normalized;
	const trimMatch = rest.match(/^let (\w+) = candidate\.trimmingCharacters\(in: \.whitespacesAndNewlines\) /);
	if (!trimMatch) throw new Error(`Handle.swift: init?(validating:) no longer starts by trimming the candidate — it starts: ${rest.slice(0, 90)}`);
	const trimmed = trimMatch[1];
	rest = rest.slice(trimMatch[0].length);

	const guardMatch = rest.match(/^guard (.+?) else \{ return nil \} /);
	if (!guardMatch) throw new Error(`Handle.swift: init?(validating:) has no \`guard … else { return nil }\` — it continues: ${rest.slice(0, 90)}`);
	rest = rest.slice(guardMatch[0].length);

	const assignMatch = rest.match(/^self\.value = (\w+) $/);
	if (!assignMatch) throw new Error(`Handle.swift: init?(validating:) does not end by assigning the trimmed candidate — it ends: ${rest.slice(0, 90)}`);
	if (assignMatch[1] !== trimmed) {
		throw new Error(`Handle.swift: init?(validating:) assigns \`${assignMatch[1]}\`, not the trimmed candidate \`${trimmed}\` — it may now normalise, which this harness cannot model`);
	}

	const rules = [{ kind: "trim" }];
	for (const condition of splitTopLevel(guardMatch[1])) {
		const empty = condition.match(/^!(\w+)\.isEmpty$/);
		if (empty && empty[1] === trimmed) {
			rules.push({ kind: "non-empty" });
			continue;
		}
		const alphabet = condition.match(/^(\w+)\.allSatisfy\(Self\.(\w+)\.contains\)$/);
		if (alphabet && alphabet[1] === trimmed) {
			const literal = source.match(new RegExp(`static let ${alphabet[2]} = Set\\("([^"]*)"\\)`));
			if (!literal) {
				throw new Error(`Handle.swift: \`${alphabet[2]}\` is not a \`Set("…")\` literal this harness can read`);
			}
			rules.push({ kind: "alphabet", name: alphabet[2], characters: new Set(literal[1]) });
			continue;
		}
		throw new Error(`Handle.swift: init?(validating:) grew a clause this harness does not understand: \`${condition}\` — teach it, or the alphabet check is measuring less than the rule`);
	}
	return rules;
}

/** Split a Swift guard's comma-separated conditions without cutting inside parentheses. */
function splitTopLevel(text) {
	const out = [];
	let depth = 0;
	let current = "";
	for (const character of text) {
		if (character === "(" || character === "[") depth += 1;
		else if (character === ")" || character === "]") depth -= 1;
		if (character === "," && depth === 0) {
			out.push(current.trim());
			current = "";
			continue;
		}
		current += character;
	}
	if (current.trim()) out.push(current.trim());
	return out;
}

/** Run the extracted rule. Returns what Swift's failable initializer would return. */
function swiftValidate(rules, candidate) {
	let value = candidate;
	for (const rule of rules) {
		if (rule.kind === "trim") value = value.replace(/^\s+|\s+$/g, "");
		if (rule.kind === "non-empty" && value.length === 0) return { accepted: false, why: "empty after trimming" };
		if (rule.kind === "alphabet") {
			for (const character of value) {
				if (!rule.characters.has(character)) {
					return { accepted: false, why: `${JSON.stringify(character)} is outside Handle's ${rule.name}` };
				}
			}
		}
	}
	return { accepted: true, value };
}

