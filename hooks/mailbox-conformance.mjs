// ── scratch space ────────────────────────────────────────────────────────────────────────

/**
 * The only place this file is allowed to write, and it is swept at exit.
 *
 * Each group tidies up after itself, but a group that THROWS mid-way does not — and a group
 * throwing is a supported outcome here, not an impossible one. Everything goes under
 * `os.tmpdir()`: nothing here ever resolves `mailRoot()` for a write, so the operator's real
 * `~/.helm/mail` — where live agents address each other — is unreachable by construction rather
 * than by care. That distinction is #133, paid for once already in pi's gate.
 */
const scratchDirectories = [];

function scratch(prefix) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
	scratchDirectories.push(dir);
	return dir;
}

process.on("exit", () => {
	for (const dir of scratchDirectories) fs.rmSync(dir, { recursive: true, force: true });
});

// ── output ───────────────────────────────────────────────────────────────────────────────

/**
 * Where check results go. A REPLACEABLE object rather than a pair of counters, because
 * `selfChecks` has to run the whole suite against a mutated source and read its failures
 * without them landing in this run's tally or on the operator's screen. Swapping the report
 * is the honest way to do that; reaching into `console.log` is not.
 */
function newReport(quiet = false) {
	return { failures: 0, checksRun: 0, lines: [], quiet };
}

let report = newReport();

function say(line) {
	report.lines.push(line);
	if (!report.quiet) console.log(line);
}

function ok(message) {
	report.checksRun += 1;
	say(`ok - ${message}`);
}

function bad(message) {
	report.checksRun += 1;
	report.failures += 1;
	say(`not ok - ${message}`);
}

function check(condition, message) {
	if (condition) ok(message);
	else bad(message);
	return condition;
}

/**
 * Run something and hand back what it wrote to stderr alongside its result.
 *
 * Only one check needs this and it needs it as its SUBJECT rather than as tidying: pi's lifted
 * code warns through `console.error` where the hook's stays silent, and "the hook writes nothing
 * to stderr" is a rule of `hooks/test.sh` worth asserting here too. Restored in a `finally`, so
 * a throwing group cannot leave the harness unable to report.
 */
function withCapturedStderr(run) {
	const lines = [];
	const real = console.error;
	console.error = (...parts) => lines.push(parts.map(String).join(" "));
	try {
		return [run(), lines];
	} finally {
		console.error = real;
	}
}

/**
 * Run something with these environment variables set — `undefined` meaning unset — and put the
 * environment back afterwards, whatever happens.
 *
 * Restoration in a `finally` is not tidiness here. Every rule under test reads its environment
 * at CALL time (`mailRoot` reads `HELM_MAIL_DIR`, `deriveHandle` reads `HELM_MAIL_HANDLE`,
 * `claudeSessionsDir` reads `CLAUDE_CONFIG_DIR`), the groups are isolated because a group
 * throwing is a supported outcome, and a group that threw mid-way used to leave
 * `CLAUDE_CONFIG_DIR` pointing at a temp registry it had already deleted — which every later
 * group would then read as "no registry at all" and report as agreement.
 */
function withEnv(values, run) {
	const before = new Map();
	for (const [name, value] of Object.entries(values)) {
		before.set(name, process.env[name]);
		if (value === undefined) delete process.env[name];
		else process.env[name] = value;
	}
	try {
		return run();
	} finally {
		for (const [name, value] of before) {
			if (value === undefined) delete process.env[name];
			else process.env[name] = value;
		}
	}
}

/**
 * Every failure this file can produce goes through `bad`, so a group that decides it has
 * nothing to compare must say so as a failure rather than return quietly. Used at the end of
 * every check group.
 */
function ranAtLeast(count, n, what) {
	check(count >= n, `${what}: ran ${count} case(s), wanted at least ${n}`);
}

// ── extraction: JavaScript ───────────────────────────────────────────────────────────────

/**
 * Lift a top-level declaration out of a source file, verbatim.
 *
 * Both files are formatted with tabs and every top-level declaration starts at column 0, so a
 * `function` block ends at the first line that is exactly `}` and a `const` ends at the first
 * line ending in `;`. That is a far more legible rule than brace counting and it fails LOUDLY
 * if the formatting ever changes, which is the property that matters: a silent mis-extraction
 * would hand the checks below a function that is not the one in the file.
 */
function extractDecl(source, file, name) {
	const lines = source.split("\n");
	const fn = new RegExp(`^(export )?(async )?function ${name}\\b`);
	const konst = new RegExp(`^(export )?const ${name}\\b`);
	for (let i = 0; i < lines.length; i++) {
		if (fn.test(lines[i])) {
			for (let j = i + 1; j < lines.length; j++) {
				if (lines[j] === "}") return lines.slice(i, j + 1).join("\n");
			}
			throw new Error(`${file}: function ${name} has no closing brace at column 0`);
		}
		if (konst.test(lines[i])) {
			for (let j = i; j < lines.length; j++) {
				if (lines[j].endsWith(";")) return lines.slice(i, j + 1).join("\n");
			}
			throw new Error(`${file}: const ${name} does not end in a semicolon`);
		}
	}
	throw new Error(`${file}: no top-level declaration named ${name} — the harness is measuring nothing`);
}

const IMPORTS = [
	'import { randomBytes } from "node:crypto";',
	'import * as fs from "node:fs";',
	'import * as os from "node:os";',
	'import * as path from "node:path";',
].join("\n");

/**
 * Build a real, importable module out of the named declarations of a real source file, and
 * return its exports. Nothing is transcribed: the declarations are the file's own bytes.
 *
 * `.mts` rather than `.ts` for pi's half, because an extension-less temp directory has no
 * `package.json` to say `"type": "module"` and `.mts` is unambiguously ESM. Node ≥ 22.6 strips
 * the type annotations on the way in; `requireTypeStripping` refuses earlier ones by name.
 *
 * Each load gets its own directory so the ESM cache cannot hand a mutated variant back the
 * unmutated module — which is exactly the failure that would make `selfChecks` pass for free.
 */
async function loadDecls({ source, file, names, extension }) {
	const dir = scratch("helm-mail-conformance-");
	const parts = names.map((name) => extractDecl(source, file, name));
	const body = `${IMPORTS}\n\n${parts.join("\n\n")}\n\nexport { ${names.join(", ")} };\n`;
	const out = path.join(dir, `lifted${extension}`);
	fs.writeFileSync(out, body, "utf8");
	// Swept by `scratch`'s exit handler rather than here: `extractDecl` above throws for a
	// missing declaration, which is a supported outcome and skipped a `finally` on this line
	// every time — measured as a dozen empty temp directories per run.
	return await import(pathToFileURL(out).href);
}

/**
 * Every top-level declaration a source makes — functions and consts both.
 *
 * BOTH HALVES, and the const half is not padding. `OFF_ENV` is `HELM_MAIL_OFF`, the kill switch
 * that is meant to silence both runtimes at once, and it is a `const` shared by both files. A
 * coverage check that only saw `function` declarations would let it be renamed or retyped in one
 * file while the operator believed both were off — the exact silent divergence this file exists
 * to catch, in the half of the grammar it was not looking at. Found in review.
 *
 * Generics are erased by the `\b`: pi declares `readJson<T>`.
 */
function topLevelDeclarationNames(source) {
	return source
		.split("\n")
		.map((line) => line.match(/^(?:export )?(?:async )?(?:function|const) ([A-Za-z0-9_]+)\b/))
		.filter(Boolean)
		.map((match) => match[1]);
}

