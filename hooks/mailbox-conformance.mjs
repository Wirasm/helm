#!/usr/bin/env node
/**
 * The mailbox's drift detector — issue #246.
 *
 *   node hooks/mailbox-conformance.mjs        (also run by `bash hooks/test.sh`)
 *
 * `AGENTS.md` permits a duplicate across a runtime boundary and attaches a condition:
 *
 *   > A duplicate is honest only when a runtime boundary makes sharing impossible … What is
 *   > **not** optional is that it be **detectable**.
 *
 * `SpoolWireConformanceTests` is the worked example for the spool. This is the mailbox's, and
 * until now the mailbox had none — while #236 widened its duplicate by three functions
 * (`sessionPid`, `ownerGone`, `retire`) and #239 added a third spelling of the handle alphabet
 * in Swift. Two surfaces:
 *
 *   1. LIVENESS AND RETIRE, `hooks/helm-mail.mjs` ↔ `pi/extensions/helm-mail/index.ts`.
 *      Not a hypothetical: the bug #236 fixed WAS two liveness rules disagreeing, twelve lines
 *      apart in one file. And each runtime reaps the OTHER's mailboxes — pi's reaper sweeps the
 *      shared root and judges Claude Code owners, the hook does the same in reverse — so a
 *      divergence here is not "pi behaves oddly", it is one runtime destroying the other's
 *      agents. `reapMatrix` below is therefore the headline check: one seeded root, both
 *      reapers, the resulting trees compared.
 *
 *   2. THE HANDLE ALPHABET, `Sources/HelmWire/Spool/Handle.swift` ↔ both writers. Swift only
 *      ever READS handles the JavaScript writers emit, so the writers are authoritative and
 *      Swift must accept what they produce, unchanged. The failure is asymmetric and worth
 *      stating: a Swift rule stricter than the writers' means helm starts refusing owner files
 *      a live agent just wrote.
 *
 * EXTRACT, DO NOT RESTATE. Every rule under test is pulled out of the real source and
 * EXECUTED — the JavaScript by lifting the named declarations verbatim into a temp module and
 * importing it, the Swift by parsing `Handle.init?(validating:)`'s own body. A harness that
 * retypes `slug`'s regex or the alphabet is a fourth copy of the rule and would go on passing
 * while the source said something else. `.claude/skills/helm-mail-cc/test.sh` (#237) is the
 * precedent; PR #244 measured the same way and caught itself being wrong about `tail`.
 *
 * WHY THIS LIVES IN `hooks/`, WHICH IS THE REAL DESIGN DECISION.
 *
 *   - It cannot live in the Swift gate. That gate is Swift-and-xcodegen by policy — `AGENTS.md`
 *     says so twice — and this needs node. `Handle`'s own header (#244) reaches the same
 *     conclusion unprompted: "It could not live in the Swift gate either … so it belongs in
 *     `hooks/test.sh` and pi's."
 *   - So a Swift constant is checked by a JavaScript test, which IS unusual. It is right here
 *     because the direction of the obligation runs that way: the writers are JavaScript and
 *     authoritative, Swift is a downstream reader, and the check is "does the reader accept
 *     what the writers emit". Only a runtime that can run the writers can generate that input,
 *     and only node can. The alternative — a checked-in corpus generated by node and consumed
 *     by a Swift test — adds a generated artifact and a second place to be stale, and buys
 *     nothing this does not already have.
 *   - Of the two node gates, `hooks/test.sh` and pi's, this belongs to `hooks/` because pi's
 *     gate is a REPO-GENERIC skill script ("run it from anywhere inside the project whose
 *     extensions are under test") and helm's mailbox is not a property of pi extensions in
 *     general. `pi/AGENTS.md` carries the pointer instead, so touching the extension still
 *     leads here.
 *   - THE COST TO `hooks/test.sh`'S PROMISE. It says "needs node and nothing else", and that
 *     stays true — but the node must now be ≥ 22.6, because reading pi's `.ts` without a build
 *     step means type stripping. That is a version floor, not a new dependency: no `tsc`, no
 *     `npm install`, no `node_modules`. An older node FAILS here rather than skipping. A skip
 *     is exactly the silent zero this ticket exists to forbid, and a gate that quietly measures
 *     nothing is worse than one that is honestly red.
 *
 * GUARD AGAINST A SILENT ZERO. Every extraction that finds nothing is a hard failure naming
 * what it looked for, every check group asserts it ran a non-zero number of cases, and
 * `selfChecks()` at the end runs the whole suite again against deliberately MUTATED copies of
 * each of the three sources and requires it to go red. That last part is what makes the guard
 * executable rather than aspirational: a harness whose teeth fall out passes its own suite.
 *
 * WHAT THIS CANNOT PROVE. Behavioural agreement over a fixture set is not proof of identical
 * code — a divergence in a case nobody thought of still ships. It is the same bargain
 * `SpoolWireConformanceTests` makes, and the fixtures are chosen to cover the cases #236
 * actually turned on rather than to be exhaustive.
 */

