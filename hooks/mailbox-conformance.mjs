/**
 * A harness that cannot find an implementation must FAIL, not pass with nothing to compare —
 * the failure mode that would make this whole file decorative. So the suite is re-run against
 * deliberately mutated copies of each source and required to go red, in this process, on every
 * run. If the teeth ever fall out, this is what notices.
 *
 * Each mutation is the smallest edit that expresses a real drift: a renamed function (the
 * extractor's silent zero), a liveness rule that disagrees, a `slug` that emits a character no
 * mailbox directory can carry, and a `Handle` rule this harness cannot model.
 */
async function selfChecks() {
	const hooksSource = fs.readFileSync(HOOKS_SOURCE, "utf8");
	const piSource = fs.readFileSync(PI_SOURCE, "utf8");
	const handleSource = fs.readFileSync(HANDLE_SOURCE, "utf8");
	const ownerSource = fs.readFileSync(OWNER_SOURCE, "utf8");
	const mutations = [
		{
			what: "a function the harness names is gone from hooks/helm-mail.mjs",
			sources: { hooksSource: hooksSource.replace(/^function ownerGone\(/m, "function ownerIsGone("), piSource, handleSource, ownerSource },
			expect: /no top-level declaration named ownerGone/,
		},
		{
			what: "a function the harness names is gone from pi's index.ts",
			sources: { hooksSource, piSource: piSource.replace(/^function sessionPid\(/m, "function sessionPidOf("), handleSource, ownerSource },
			expect: /no top-level declaration named sessionPid/,
		},
		{
			what: "pi's ownerGone stops asking the registry — the exact shape of the #236 bug",
			sources: {
				hooksSource,
				piSource: piSource.replace(
					'if (owner.runtime === "claude" && owner.sessionId && sessionPid(owner.sessionId)) return false;',
					"",
				),
				handleSource,
				ownerSource,
			},
			expect: /ownerGone disagrees|both reapers leave the SAME shared root/,
		},
		{
			what: "the hook's slug emits a character no mailbox directory can carry",
			sources: { hooksSource: hooksSource.replace('.replace(/[^a-z0-9]+/g, "-")', '.replace(/[^a-z0-9]+/g, "_")'), piSource, handleSource, ownerSource },
			expect: /slug agrees|deriveHandle agrees|accepts all/,
		},
		{
			what: "a fourth rule is added to both mailbox files and nobody tells this harness",
			sources: {
				hooksSource: `${hooksSource}\nfunction aFourthSharedRule() {\n\treturn 1;\n}\n`,
				piSource: `${piSource}\nfunction aFourthSharedRule() {\n\treturn 1;\n}\n`,
				handleSource,
				ownerSource,
			},
			expect: /not classified: aFourthSharedRule/,
		},
		{
			// The const half of the same guard, separately, because the function half passing says
			// nothing about it — that gap is what review found, and `OFF_ENV` is what it hid.
			what: "a fourth shared CONST is added to both mailbox files and nobody tells this harness",
			sources: {
				hooksSource: `${hooksSource}\nconst A_FOURTH_SHARED_CONST = "x";\n`,
				piSource: `${piSource}\nconst A_FOURTH_SHARED_CONST = "x";\n`,
				handleSource,
				ownerSource,
			},
			expect: /not classified: A_FOURTH_SHARED_CONST/,
		},
		{
			what: "MailboxOwner starts requiring a field neither writer's claim() writes",
			sources: {
				hooksSource,
				piSource,
				handleSource,
				ownerSource: ownerSource.replace(
					"retiredAt = try container.decodeIfPresent(Double.self, forKey: .retiredAt)",
					"retiredAt = try container.decode(Double.self, forKey: .retiredAt)",
				),
			},
			expect: /MailboxOwner requires "retiredAt"/,
		},
		{
			what: "MailboxOwner's init grows a statement the harness cannot model",
			sources: {
				hooksSource,
				piSource,
				handleSource,
				ownerSource: ownerSource.replace(
					"        pid = try container.decode(pid_t.self, forKey: .pid)",
					"        pid = pid_t(try container.decode(String.self, forKey: .pid)) ?? 0",
				),
			},
			expect: /grew a statement this harness does not understand/,
		},
		{
			what: "Handle's rule grows a clause the harness cannot model",
			sources: {
				hooksSource,
				piSource,
				ownerSource,
				handleSource: handleSource.replace(
					"guard !trimmed.isEmpty",
					"guard !trimmed.isEmpty, trimmed.count < 64",
				),
			},
			expect: /does not understand/,
		},
	];

	for (const mutation of mutations) {
		// A mutation that no longer matches its source is a no-op, and a no-op mutation makes its
		// self-check pass for exactly the wrong reason. Caught here rather than left to look like
		// a harness that has lost its teeth. (It fires for real: mutating the hook's `slug` is a
		// no-op if pi's has already been mutated the same way, which is how this was measured.)
		const changed =
			mutation.sources.hooksSource !== hooksSource ||
			mutation.sources.piSource !== piSource ||
			mutation.sources.handleSource !== handleSource ||
			mutation.sources.ownerSource !== ownerSource;
		if (!check(changed, `self-check: the mutation for "${mutation.what}" still applies to today's source`)) continue;

		const real = report;
		report = newReport(true);
		let thrown;
		try {
			await runConformance(mutation.sources);
		} catch (error) {
			thrown = error;
		}
		const mutated = report;
		report = real;

		const complaints = mutated.lines.filter((line) => line.startsWith("not ok"));
		const noise = [...complaints, thrown ? `threw: ${thrown.message}` : ""].join(" | ");
		const wentRed = thrown !== undefined || complaints.length > 0;
		if (!check(wentRed && mutation.expect.test(noise), `self-check: the suite goes red when ${mutation.what}`)) {
			say(`#   what it actually said: ${noise.slice(0, 400) || "(nothing — the suite stayed green)"}`);
		}
	}
}

// ── main ─────────────────────────────────────────────────────────────────────────────────

/**
 * Reading pi's `.ts` with no build step needs node ≥ 22.6. FAIL rather than skip: a skip here
 * is the silent zero this file exists to forbid, and `hooks/test.sh`'s "needs node and nothing
 * else" survives a version floor — no tsc, no npm install, no node_modules.
 */
function requireTypeStripping() {
	if (process.features.typescript) return;
	bad(`node ${process.version} cannot strip TypeScript; this needs node >= 22.6 (no other dependency)`);
	say("# 1 of 1 check(s) failed");
	process.exit(1);
}

async function main() {
	requireTypeStripping();
	for (const [what, file] of [["hooks", HOOKS_SOURCE], ["pi", PI_SOURCE], ["Handle", HANDLE_SOURCE], ["MailboxOwner", OWNER_SOURCE]]) {
		if (!fs.existsSync(file)) {
			bad(`the ${what} implementation is not at ${file} — refusing to pass with nothing to compare`);
			say("# 1 of 1 check(s) failed");
			process.exit(1);
		}
	}

	try {
		await runConformance({
			hooksSource: fs.readFileSync(HOOKS_SOURCE, "utf8"),
			piSource: fs.readFileSync(PI_SOURCE, "utf8"),
			handleSource: fs.readFileSync(HANDLE_SOURCE, "utf8"),
			ownerSource: fs.readFileSync(OWNER_SOURCE, "utf8"),
		});
	} catch (error) {
		bad(`the harness could not run: ${error.message}`);
	}

	// Only when the real sources are clean. A mutation of an already-drifted source proves
	// nothing, and running them anyway buries the real failure under five derived ones — which
	// is what it did the first time this was measured.
	if (report.failures === 0) await selfChecks();
	else say(`# skipping the self-checks: ${report.failures} real failure(s) above, and a mutation of a drifted source proves nothing`);

	// The last silent-zero guard, and the crudest: a suite that returned early somewhere above
	// still reports "ok" on every line it did reach. This is the floor it cannot get under.
	if (report.checksRun < 40) {
		bad(`only ${report.checksRun} checks ran; this file is meant to run far more, so something returned early`);
	}
	if (report.failures > 0) {
		say(`# ${report.failures} of ${report.checksRun} check(s) failed`);
		process.exit(1);
	}
	say(`# mailbox conformance ok — ${report.checksRun} checks`);
}

await main();
